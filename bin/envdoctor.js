#!/usr/bin/env node
/** envdoctor CLI — zero dependencies. */
import fs from 'node:fs';
import path from 'node:path';
import { parseDotenv } from '../src/parser.js';
import { checkEnvFiles, formatHuman, formatJson, hasErrors, summarize } from '../src/check.js';
import { collectCodeRefs } from '../src/scan.js';
import { gitSafety } from '../src/gitcheck.js';
import { scanValue } from '../src/secrets.js';

const VERSION = '0.1.0';

function printHelp() {
  console.log([
    'envdoctor ' + VERSION + ' — dotenv + env usage checker',
    '',
    'Usage:',
    '  envdoctor check [options] [projectDir]',
    '  envdoctor init [--force]',
    '  envdoctor --help | --version',
    '',
    'Commands:',
    '  check    Validate .env against code usage and .env.example (default)',
    '  init     Create a starter .env.example from .env keys (redacted)',
    '',
    'Options:',
    '  --env <file>        Env file to check (default: .env)',
    '  --example <file>    Example file to compare (default: .env.example if present)',
    '  --no-scan           Skip source-code usage scan',
    '  --json              Output JSON report',
    '  --strict            Exit non-zero on warnings too',
    '  --allow-unused K    Comma-separated keys exempt from unused-key info',
    '  --no-git-check      Skip gitignore/tracked-file safety checks',
    '  --no-secret-scan    Skip real-secret detection',
    '',
    'Exit codes: 0 clean (or warnings without --strict), 1 errors (or warnings with --strict), 2 usage/IO error.',
  ].join('\n'));
}

function parseArgs(argv) {
  const args = { cmd: 'check', dir: process.cwd(), env: '.env', example: null, exampleAuto: true,
    scan: true, json: false, strict: false, allowUnused: [], gitCheck: true, secretScan: true };
  const rest = [...argv];
  if (rest[0] === 'check' || rest[0] === 'init') args.cmd = rest.shift();
  while (rest.length) {
    const a = rest.shift();
    if (a === '--help' || a === '-h') { printHelp(); process.exit(0); }
    else if (a === '--version' || a === '-v') { console.log(VERSION); process.exit(0); }
    else if (a === '--env') args.env = rest.shift() ?? fail('--env needs a value');
    else if (a.startsWith('--env=')) args.env = a.slice(6);
    else if (a === '--example') { args.example = rest.shift() ?? fail('--example needs a value'); args.exampleAuto = false; }
    else if (a.startsWith('--example=')) { args.example = a.slice(10); args.exampleAuto = false; }
    else if (a === '--no-scan') args.scan = false;
    else if (a === '--json') args.json = true;
    else if (a === '--strict') args.strict = true;
    else if (a === '--no-git-check') args.gitCheck = false;
    else if (a === '--no-secret-scan') args.secretScan = false;
    else if (a === '--allow-unused') {
      const v = rest.shift() ?? fail('--allow-unused needs a value');
      args.allowUnused.push(...v.split(',').map(s => s.trim()).filter(Boolean));
    }
    else if (a.startsWith('--allow-unused=')) args.allowUnused.push(...a.slice(15).split(',').map(s => s.trim()).filter(Boolean));
    else if (a === '--force') args.force = true;
    else if (a.startsWith('-')) fail(`Unknown option: ${a}`);
    else args.dir = a;
  }
  return args;
}

function fail(msg) { console.error('envdoctor: ' + msg); process.exit(2); }

function redact(value) {
  if (value == null || value === '') return '';
  return 'CHANGEME';
}

async function cmdInit(cwd, force) {
  const envPath = path.join(cwd, '.env');
  const exPath = path.join(cwd, '.env.example');
  if (!fs.existsSync(envPath)) fail('No .env found in ' + cwd);
  if (fs.existsSync(exPath) && !force) fail('.env.example already exists (use --force to overwrite)');
  const text = await fs.promises.readFile(envPath, 'utf8');
  const entries = parseDotenv(text);
  const out = ['# Example environment — copy to .env and fill in real values.', '# Generated by `envdoctor init`.', ''];
  for (const e of entries) {
    if (e.invalid || e.key == null) continue;
    out.push(`${e.key}=${redact(e.value)}`);
  }
  out.push('');
  await fs.promises.writeFile(exPath, out.join('\n'));
  console.log(`envdoctor: wrote ${exPath} (${out.length - 4} keys)`);
}

async function cmdCheck(args) {
  const dir = path.resolve(args.dir);
  const envPath = path.isAbsolute(args.env) ? args.env : path.join(dir, args.env);
  let examplePath = null;
  if (args.example) examplePath = path.isAbsolute(args.example) ? args.example : path.join(dir, args.example);
  else if (args.exampleAuto) {
    const auto = path.join(dir, '.env.example');
    if (fs.existsSync(auto)) examplePath = auto;
  }
  let envText;
  try { envText = await fs.promises.readFile(envPath, 'utf8'); }
  catch { fail(`Cannot read env file: ${envPath}`); }
  let exampleText = null;
  if (examplePath) {
    try { exampleText = await fs.promises.readFile(examplePath, 'utf8'); }
    catch { fail(`Cannot read example file: ${examplePath}`); }
  }
  let codeRefs = null;
  if (args.scan) {
    try { codeRefs = await collectCodeRefs(dir); }
    catch (e) { fail('Code scan failed: ' + (e && e.message)); }
  }
  const result = checkEnvFiles({ envText, exampleText, codeRefs,
    options: { allowUnused: args.allowUnused } });
  if (args.secretScan) {
    for (const e of result.entries) {
      if (e.invalid || e.key == null) continue;
      const f = scanValue(e.key, e.value);
      if (f) { f.lines = [e.line]; result.issues.push(f); }
    }
  }
  if (args.gitCheck) {
    const rel = path.relative(dir, envPath) || '.env';
    const g = await gitSafety(dir, rel);
    result.issues.push(...g.findings);
  }
  const counts = summarize(result.issues);
  if (args.json) {
    console.log(formatJson(result, { env: envPath, example: examplePath, version: VERSION, counts }));
  } else {
    console.log(formatHuman(result, { envPath, examplePath }));
  }
  const bad = hasErrors(result) || (args.strict && (counts.warning > 0 || counts.info > 0));
  process.exit(bad ? 1 : 0);
}

const args = parseArgs(process.argv.slice(2));
if (args.cmd === 'init') await cmdInit(path.resolve(args.dir), args.force);
else await cmdCheck(args);
